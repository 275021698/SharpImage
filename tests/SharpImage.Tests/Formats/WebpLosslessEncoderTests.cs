        (string Tag, float Q, int M, bool Exact, int Near)[] configs =
        [
            ("ll", 75, 4, false, 100), ("ll_m0", 0, 0, false, 100), ("ll_m6", 100, 6, false, 100),
            ("ll_m5", 90, 5, false, 100), ("ll_exact", 75, 4, true, 100), ("ll_near60", 75, 4, false, 60),
        ];
        foreach (var n in names)
            foreach (var c in configs)
                yield return (n, c.Tag, c.Q, c.M, c.Exact, c.Near);
    }

