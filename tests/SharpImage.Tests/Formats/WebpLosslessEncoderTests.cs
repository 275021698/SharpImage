    public async Task PrefixEncode_MatchesLibwebpTables()
    {
        int bad = 0;
        for (int d = 0; d < 512; d++)
        {
            Vp8lCommon.PrefixEncode(d, out int code, out int extraBits, out int value);
            if (code != PrefixCode[d] || extraBits != PrefixExtraBits[d] || value != PrefixExtraBitsValue[d]) bad++;
        }
